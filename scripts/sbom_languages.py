"""Generate CycloneDX SBOMs for the non-Python FlowSemantics implementations.

SPEC 15.3: every release MUST include a CycloneDX or SPDX SBOM listing
every build-time and development-time dependency with version and
license. The Python SBOM is generated by scripts/sbom.py; this script
covers TypeScript, Go, Java, and C#/.NET.

Usage:
    python scripts/sbom_languages.py

Writes sbom.typescript.cdx.json, sbom.go.cdx.json, sbom.java.cdx.json,
and sbom.csharp.cdx.json at the repository root. Stdlib only.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def _bom(name: str, serial: str, components: list[dict]) -> dict:
    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "serialNumber": serial,
        "version": 1,
        "metadata": {
            "component": {"type": "application", "name": name, "version": "0.0.0"},
            "timestamp": "2026-11-23T00:00:00Z",
            "tools": [{"name": "scripts/sbom_languages.py", "version": "1.0"}],
        },
        "components": components,
    }


def _dep(name: str, purl: str, version: str, scope: str = "excluded") -> dict:
    return {
        "type": "library",
        "name": name,
        "version": version,
        "purl": purl,
        "scope": scope,
    }


def typescript_components() -> list[dict]:
    """Resolved versions from typescript/package-lock.json (dev deps)."""
    lock = json.loads((REPO_ROOT / "typescript" / "package-lock.json").read_text())
    pkgs = lock.get("packages", {})
    out = []
    for path, meta in sorted(pkgs.items()):
        if not path:
            continue  # root package
        name = path.removeprefix("node_modules/")
        version = meta.get("version", "unresolved")
        out.append(_dep(name, f"pkg:npm/{name}@{version}", version))
    return out


def main() -> None:
    boms = {
        "typescript": _bom(
            "flow-semantics-ts",
            "urn:uuid:flowsemantics-typescript-sbom",
            typescript_components(),
        ),
        "go": _bom(
            "flowsemantics-go",
            "urn:uuid:flowsemantics-go-sbom",
            [],  # go.mod declares zero third-party dependencies
        ),
        "java": _bom(
            "flowsemantics-java",
            "urn:uuid:flowsemantics-java-sbom",
            [],  # zero third-party dependencies (hand-written JSON parser)
        ),
        "csharp": _bom(
            "flowsemantics-csharp",
            "urn:uuid:flowsemantics-csharp-sbom",
            [],  # net10.0 in-box only; zero PackageReferences
        ),
    }
    for lang, bom in boms.items():
        path = REPO_ROOT / f"sbom.{lang}.cdx.json"
        path.write_text(json.dumps(bom, indent=2) + "\n")
        print(f"wrote {path.name}: {len(bom['components'])} component(s)")


if __name__ == "__main__":
    main()
